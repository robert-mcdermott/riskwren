#!/usr/bin/env python3
"""Draft the next migration from the models.

Builds a scratch SQLite database at the current head, compares it with what the models
describe, and writes the difference as a numbered revision for a person to read and tidy:

    uv run python scripts/new-migration.py 0004 "Inventory: processes, systems, third parties"

A test already fails when migrations and models disagree; this only saves the typing.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

from alembic import command
from sqlalchemy import create_engine

import riskwren.db.models  # noqa: F401  (registers every model)
from riskwren.db import migrate


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    revision, message = argv
    with tempfile.TemporaryDirectory() as folder:
        url = f"sqlite:///{folder}/scratch.db"
        engine = create_engine(url)
        migrate.upgrade(engine)
        engine.dispose()
        script = command.revision(
            migrate.alembic_config(url), message=message, autogenerate=True, rev_id=revision
        )
    assert script is not None and not isinstance(script, list)
    path = Path(script.path)
    text = path.read_text(encoding="utf-8")
    for noise in (
        "from sqlalchemy.dialects import postgresql\n",
        "    # ### commands auto generated by Alembic - please adjust! ###\n",
        "    # ### end Alembic commands ###\n",
    ):
        text = text.replace(noise, "")
    for rendered in (
        "sa.JSON().with_variant(postgresql.JSONB(astext_type=Text()), 'postgresql')",
        "sa.JSON().with_variant(postgresql.JSONB(astext_type=sa.Text()), 'postgresql')",
    ):
        text = text.replace(rendered, "riskwren.db.types.JsonType")  # the portable type
    path.write_text(text, encoding="utf-8")
    subprocess.run(["uv", "run", "ruff", "format", "-q", str(path)], check=False)
    print(f"Drafted {path}. Read it, name it, and seed any new reference counters.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
